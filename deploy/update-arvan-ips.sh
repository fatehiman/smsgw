#!/bin/bash
# Refresh the list of ArvanCloud CDN addresses that Apache may trust for AR-Real-IP.
# Runs on the server (weekly via /etc/cron.weekly/smsgw-arvan-ips). Keeps the old list if the download fails.
set -euo pipefail
OUT=/etc/apache2/smsgw-arvan-ips.conf
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

curl -fsS -m 30 https://www.arvancloud.ir/en/ips.txt \
  | tr -d '\r' | grep -E '^[0-9a-fA-F:.]+(/[0-9]+)?$' > "$TMP" || true

if [ "$(wc -l < "$TMP")" -lt 5 ]; then
  echo "arvan ip list download failed or too short; keeping $OUT" >&2
  [ -s "$OUT" ] && exit 0
  exit 1
fi

{
  echo "# Generated by update-arvan-ips.sh on $(date -u +%FT%TZ). Do not edit."
  sed 's/^/RemoteIPTrustedProxy /' "$TMP"
} > "$OUT.new"

if ! cmp -s "$OUT.new" "$OUT" 2>/dev/null; then
  mv "$OUT.new" "$OUT"
  apache2ctl configtest >/dev/null 2>&1 && systemctl reload apache2
else
  rm -f "$OUT.new"
fi
